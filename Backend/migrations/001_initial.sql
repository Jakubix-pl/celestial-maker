CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY,user_id TEXT NOT NULL,expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS login_flows(token TEXT PRIMARY KEY,verifier TEXT NOT NULL,state TEXT NOT NULL,expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS orders(request_id TEXT PRIMARY KEY,user_id TEXT NOT NULL,product TEXT NOT NULL,session_id TEXT UNIQUE,url TEXT);
CREATE TABLE IF NOT EXISTS events(id TEXT PRIMARY KEY,created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS transactions(id TEXT PRIMARY KEY,user_id TEXT NOT NULL,product TEXT NOT NULL,status TEXT NOT NULL,created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS revocations(id TEXT PRIMARY KEY,reason TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS activations(id TEXT PRIMARY KEY,transaction_id TEXT UNIQUE NOT NULL REFERENCES transactions(id),user_id TEXT NOT NULL,start INTEGER NOT NULL,end INTEGER NOT NULL);
